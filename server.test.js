import assert from 'node:assert/strict';
import { once } from 'node:events';
import { mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { parse } from 'yaml';
import { makeServer } from './server.js';

test('groups use separate YAML files, reject stale saves, and survive reload', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'santa-test-'));
  const server = makeServer(directory).listen(0, '127.0.0.1');
  t.after(async () => {
    await new Promise(resolve => server.close(resolve));
    await rm(directory, { recursive: true });
  });
  await once(server, 'listening');
  const base = `http://127.0.0.1:${server.address().port}`;
  const send = (path, method = 'GET', data) => fetch(base + path, { method, ...(data && { headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(data) }) });
  const api = '/api/groups';
  assert.deepEqual(await (await send(api)).json(), { groups: [], warnings: [] });
  const first = await send(api, 'POST', { name: 'Natal: 2026' });
  assert.equal(first.status, 201);
  const { id, revision, group } = await first.json();
  const second = await (await send(api, 'POST', { name: 'Friends' })).json();
  assert.notEqual(second.id, id);
  const path = `${api}/${id}`;
  group.participants = ['Alice', 'Bob', 'Charlie'];
  group.pairs = [{ giver: 'Alice', recipient: 'Bob', state: 'confirmed' }, { giver: 'Charlie', recipient: 'Alice', state: 'more' }];
  const updated = await send(path, 'PUT', { revision, group });
  assert.equal(updated.status, 200);
  const envelope = await updated.json();
  assert.notEqual(revision, envelope.revision);
  assert.deepEqual(parse(await readFile(join(directory, id), 'utf8')), group);
  assert.deepEqual(await (await send(path)).json(), envelope);
  assert.deepEqual(await (await send(path, 'PUT', { revision, group })).json(), envelope);
  assert.equal((await send(path, 'PUT', { revision, group: { ...group, name: 'Stale' } })).status, 409);
  assert.equal((await send(path, 'PUT', { revision: envelope.revision, group: { ...group, participants: ['A', 'A'] } })).status, 400);
  const contenders = await Promise.all(['Left', 'Right'].map(name => send(path, 'PUT', { revision: envelope.revision, group: { ...group, name } })));
  assert.deepEqual(contenders.map(response => response.status).sort(), [200, 409]);
  assert.deepEqual((await readdir(directory)).sort(), [id, second.id].sort());
  await writeFile(join(directory, 'bad.yaml'), 'invalid YAML group');
  await writeFile(join(directory, 'other.yml'), 'name: Other\nparticipants: []\nteam: false\npairs: []\n');
  const listing = await (await send(api)).json();
  assert.equal(listing.groups.length, 3);
  assert.equal(listing.warnings.length, 1);
  await writeFile(join(directory, 'old.yaml'), 'name: Old\nparticipants: []\npairs: []\nhunches: []\n');
  assert.equal((await (await send(api)).json()).warnings.length, 2);
  assert.equal((await fetch(base + api, { headers: { Origin: 'https://other.example' } })).status, 403);
  assert.equal((await send('/')).status, 200);
  assert.equal((await send('/data/' + id)).status, 404);

  const participants = Array.from({ length: 18 }, (_, i) => `${'字'.repeat(79)}${String.fromCharCode(65 + i)}`);
  const edges = participants.flatMap(giver => participants.filter(recipient => recipient !== giver).map(recipient => ({ giver, recipient })));
  const denseGroup = { ...second.group, participants, pairs: edges.map(edge => ({ ...edge, state: 'excluded' })) };
  const denseSave = await send(`${api}/${second.id}`, 'PUT', { revision: second.revision, group: denseGroup });
  assert.equal(denseSave.status, 200);
  assert.deepEqual((await denseSave.json()).group, denseGroup);
});
